import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const workspace = path.dirname(scriptDirectory);
const productDirectory = path.join(workspace, 'public', 'images', 'products');
const docsDirectory = path.join(workspace, 'docs');
const fallbackFile = 'fallback.svg';
const sourceFiles = [
  path.join(workspace, 'lib', 'fragrances.ts'),
  path.join(workspace, 'lib', 'fragrance-expansion.ts'),
  path.join(workspace, 'lib', 'brand-expansion.ts'),
  path.join(workspace, 'lib', 'catalog-completion.ts'),
];

const ids = [];
for (const file of sourceFiles) {
  const source = await fs.readFile(file, 'utf8');
  ids.push(...[...source.matchAll(/^\s+id: '([^']+)',?$/gm)].map(match => match[1]));
  ids.push(...[...source.matchAll(
    /^\s+\[\r?\n\s+'([^']+)',\r?\n\s+(?:'[^']+'|"[^"]+"),\r?\n\s+'[^']+',/gm,
  )].map(match => match[1]));
  if (file.endsWith('catalog-completion.ts')) {
    ids.push(...[...source.matchAll(
      /^\s+\['(?:Zoologist|Maison Margiela|Maison Francis Kurkdjian|Tom Ford|Initio Parfums Privés|Louis Vuitton|Goldfield & Banks|Parfums de Marly|Yves Saint Laurent|Dior|Xerjoff|Chanel|Diptyque)',\s+'([^']+)',/gm,
    )].map(match => match[1]));
  }
}

const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
if (duplicates.length) {
  throw new Error(`Duplicate fragrance IDs: ${[...new Set(duplicates)].join(', ')}`);
}

const manifest = JSON.parse(
  await fs.readFile(path.join(productDirectory, 'sources.json'), 'utf8'),
);
const sourceById = new Map(manifest.map(source => [source.id, source]));
const minimumProductImageSize = 480;

// A fragrance is "recommendable" only when it resolves to a real, adequately
// sized local packshot. Anything else is temporarily excluded from
// recommendations, browsing, search and the Shelf (see recommendableFragrances
// in lib/fragrances.ts) and is reported below rather than shown with generic
// imagery. This validation FAILS when any recommendable fragrance uses the
// fallback, points at a missing/undersized file, or shares another
// fragrance's image.
const failures = [];
const missingImageIds = [];
const imageOwners = new Map(); // file basename -> id
const contentHashOwners = new Map(); // sha256 of bytes -> id

for (const id of ids) {
  const source = sourceById.get(id);
  const hasUsableSource = source
    && source.status === 'OK'
    && source.file
    && source.file !== fallbackFile
    && source.pageUrl;

  if (!hasUsableSource) {
    missingImageIds.push(id);
    continue;
  }

  const filePath = path.join(productDirectory, source.file);
  let bytes;
  try {
    bytes = await fs.readFile(filePath);
  } catch {
    // Manifest promises a real image but the file is gone: this IS a broken
    // recommendable entry, so fail rather than silently excluding it.
    failures.push(`${id}: manifest marks image "${source.file}" OK but the file is missing`);
    continue;
  }

  try {
    const metadata = await sharp(bytes).metadata();
    if (
      !metadata.width
      || !metadata.height
      || metadata.width < minimumProductImageSize
      || metadata.height < minimumProductImageSize
    ) {
      failures.push(
        `${id}: expected product image at least ${minimumProductImageSize}px on each side, received ${metadata.width}x${metadata.height}`,
      );
      continue;
    }
  } catch {
    failures.push(`${id}: product image file is unreadable (${source.file})`);
    continue;
  }

  const existingByName = imageOwners.get(source.file);
  if (existingByName) {
    failures.push(`${id}: reuses ${existingByName}'s image file "${source.file}"`);
  } else {
    imageOwners.set(source.file, id);
  }

  const contentHash = crypto.createHash('sha256').update(bytes).digest('hex');
  const existingByHash = contentHashOwners.get(contentHash);
  if (existingByHash && existingByHash !== id) {
    failures.push(`${id}: image bytes are identical to ${existingByHash} (${source.file})`);
  } else {
    contentHashOwners.set(contentHash, id);
  }
}

const orphanedSources = manifest
  .filter(source => source.status === 'OK' && source.file && source.file !== fallbackFile)
  .filter(source => !ids.includes(source.id))
  .map(source => source.id);
if (orphanedSources.length) {
  failures.push(`orphaned manifest entries: ${orphanedSources.join(', ')}`);
}

// Always publish the list of catalogue IDs still awaiting a real photograph so
// the coverage gap is visible and tracked.
await fs.mkdir(docsDirectory, { recursive: true });
const reportLines = [
  '# Fragrances awaiting real product photography',
  '',
  '> Generated by `npm run validate:catalog`. Do not edit by hand.',
  '',
  `- Catalogue size: **${ids.length}**`,
  `- With a real local packshot (recommendable): **${ids.length - missingImageIds.length}**`,
  `- Awaiting a real photograph (excluded from recommendations/browsing/search/Shelf): **${missingImageIds.length}**`,
  '',
  '## IDs still needing a genuine bottle photo',
  '',
  ...(missingImageIds.length
    ? missingImageIds.map(id => `- ${id}`)
    : ['_None — full coverage._']),
  '',
];
await fs.writeFile(
  path.join(docsDirectory, 'missing-product-images.md'),
  `${reportLines.join('\n')}\n`,
);

if (failures.length) {
  throw new Error(`Catalog validation failed:\n${failures.join('\n')}`);
}

console.log(
  `Catalog valid: ${ids.length} fragrances, ${imageOwners.size} with unique real packshots (recommendable), ${missingImageIds.length} awaiting photography (see docs/missing-product-images.md).`,
);
